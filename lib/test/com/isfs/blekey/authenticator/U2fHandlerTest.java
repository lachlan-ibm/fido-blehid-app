    @Test
    public void registerWithSpecInputsReturnsWellFormedSignedResponse() throws Exception {
        RegistrationBody r = register();

        assertEquals(65, r.pub.length);
        assertEquals(84, r.keyHandle.length, "prefix(4)+iv(16)+ciphertext(64)");
        assertArrayEquals("U2FH".getBytes(StandardCharsets.US_ASCII),
            Arrays.copyOf(r.keyHandle, 4));

        // §4.3 signed message: 0x00 || appParam || challengeParam || keyHandle || userPublicKey
        byte[] signed = concat(new byte[] {0x00}, APP_PARAM, CHALLENGE, r.keyHandle, r.pub);
        assertTrue(verify(publicKeyFromPoint(r.pub), signed, r.sig),
            "registration signature must verify with the returned user public key");

        // attestation cert carries the same user public key
        X509Certificate cert = parseCert(r.cert);
        assertEquals(publicKeyFromPoint(r.pub), cert.getPublicKey());
        assertTrue(r.sig.length >= 8 && r.sig.length <= 72);
    }

