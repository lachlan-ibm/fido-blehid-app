    @Test
    public void normalizeTo32HandlesAllLengths() throws Exception {
        byte[] exact = new byte[32];
        Arrays.fill(exact, (byte) 0xAB);
        assertArrayEquals(exact, normalizeTo32(exact));

        // BigInteger.toByteArray() sign byte: 33 bytes, leading 0x00 dropped
        assertArrayEquals(exact, normalizeTo32(concat(new byte[] {0x00}, exact)));

        // short values are left-padded with zeros
        byte[] expected = new byte[32];
        expected[31] = 0x7F;
        assertArrayEquals(expected, normalizeTo32(new byte[] {0x7F}));

        byte[] shortVal = new byte[31];
        Arrays.fill(shortVal, (byte) 0x01);
        byte[] padded = normalizeTo32(shortVal);
        assertEquals(0x00, padded[0]);
        assertArrayEquals(shortVal, Arrays.copyOfRange(padded, 1, 32));

        assertArrayEquals(new byte[32], normalizeTo32(new byte[0]));
    }

