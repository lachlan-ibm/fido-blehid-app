    private static byte[] hex(String s) {
        String h = s.replaceAll("\\s", "");
        byte[] out = new byte[h.length() / 2];
        for (int i = 0; i < out.length; i++) {
            out[i] = (byte) Integer.parseInt(h.substring(2 * i, 2 * i + 2), 16);
        }
        return out;
    }

    private static byte[] concat(byte[]... parts) {
        int n = 0;
        for (byte[] p : parts) n += p.length;
        byte[] out = new byte[n];
        int off = 0;
        for (byte[] p : parts) {
            System.arraycopy(p, 0, out, off, p.length);
            off += p.length;
        }
        return out;
    }

    private static byte[] stripSuccessSw(byte[] rsp) {
        assertNotNull(rsp);
        assertTrue(rsp.length > 2, "response too short: " + rsp.length);
        assertEquals((byte) 0x90, rsp[rsp.length - 2], "SW1");
        assertEquals((byte) 0x00, rsp[rsp.length - 1], "SW2");
        return Arrays.copyOf(rsp, rsp.length - 2);
    }

    /** Total length (header + content) of the DER SEQUENCE starting at {@code off}. */
    private static int derTotalLength(byte[] b, int off) {
        assertEquals(0x30, b[off] & 0xFF, "expected DER SEQUENCE");
        int l = b[off + 1] & 0xFF;
        if (l < 0x80) return 2 + l;
        int n = l & 0x7F;
        int len = 0;
        for (int i = 0; i < n; i++) len = (len << 8) | (b[off + 2 + i] & 0xFF);
        return 2 + n + len;
    }

    /** U2F Raw Message Formats §4.3 registration response body (no status word). */
    private static final class RegistrationBody {
        byte[] pub;
        byte[] keyHandle;
        byte[] cert;
        byte[] sig;

        static RegistrationBody parse(byte[] body) {
            assertEquals(0x05, body[0] & 0xFF, "reserved byte");
            RegistrationBody r = new RegistrationBody();
            r.pub = Arrays.copyOfRange(body, 1, 66);
            assertEquals(0x04, r.pub[0] & 0xFF, "uncompressed point prefix");
            int khLen = body[66] & 0xFF;
            r.keyHandle = Arrays.copyOfRange(body, 67, 67 + khLen);
            int off = 67 + khLen;
            int certLen = derTotalLength(body, off);
            r.cert = Arrays.copyOfRange(body, off, off + certLen);
            off += certLen;
            r.sig = Arrays.copyOfRange(body, off, body.length);
            return r;
        }
    }

    /** U2F Raw Message Formats §5.4 authentication response body (no status word). */
    private static final class AuthenticationBody {
        int userPresence;
        long counter;
        byte[] sig;

        static AuthenticationBody parse(byte[] body) {
            AuthenticationBody a = new AuthenticationBody();
            a.userPresence = body[0] & 0xFF;
            a.counter = ByteBuffer.wrap(body, 1, 4).getInt() & 0xFFFFFFFFL;
            a.sig = Arrays.copyOfRange(body, 5, body.length);
            return a;
        }
    }

    private static PublicKey publicKeyFromPoint(byte[] pub65) throws Exception {
        AlgorithmParameters ap = AlgorithmParameters.getInstance("EC");
        ap.init(new ECGenParameterSpec("secp256r1"));
        ECParameterSpec spec = ap.getParameterSpec(ECParameterSpec.class);
        ECPoint w = new ECPoint(
            new BigInteger(1, Arrays.copyOfRange(pub65, 1, 33)),
            new BigInteger(1, Arrays.copyOfRange(pub65, 33, 65)));
        return KeyFactory.getInstance("EC").generatePublic(new ECPublicKeySpec(w, spec));
    }

    private static boolean verify(PublicKey pk, byte[] msg, byte[] derSig) throws Exception {
        Signature s = Signature.getInstance("SHA256withECDSA");
        s.initVerify(pk);
        s.update(msg);
        return s.verify(derSig);
    }

    private static X509Certificate parseCert(byte[] der) throws Exception {
        return (X509Certificate) CertificateFactory.getInstance("X.509")
            .generateCertificate(new ByteArrayInputStream(der));
    }

    private static CtapTxn newTxn() {
        CtapTxn txn = new CtapTxn();
        txn.setCid(new byte[] {0x7F, 0x00, 0x00, 0x01});
        return txn;
    }

    private RegistrationBody register() throws Exception {
        armGrant();
        byte[] rsp = U2fHandler.u2fRegister(newTxn(), CHALLENGE, APP_PARAM);
        return RegistrationBody.parse(stripSuccessSw(rsp));
    }

