    @Test
    public void specRegistrationResponseLayoutParsesWithHandlerFraming() throws Exception {
        byte[] body = concat(
            new byte[] {0x05}, hex(SPEC_USER_PUB_KEY),
            new byte[] {(byte) hex(SPEC_KEY_HANDLE).length}, hex(SPEC_KEY_HANDLE),
            hex(SPEC_ATTESTATION_CERT), hex(SPEC_REGISTER_SIG));

        RegistrationBody r = RegistrationBody.parse(body);

        assertEquals(65, r.pub.length);
        assertEquals(64, r.keyHandle.length);
        assertEquals(590, r.cert.length);
        assertArrayEquals(hex(SPEC_KEY_HANDLE), r.keyHandle);
        assertArrayEquals(hex(SPEC_ATTESTATION_CERT), r.cert);
        assertArrayEquals(hex(SPEC_REGISTER_SIG), r.sig);
        assertTrue(r.sig.length >= 8 && r.sig.length <= 72, "DER ECDSA signature is 8-72 bytes");
        assertTrue(parseCert(r.cert).getSubjectX500Principal().getName()
            .contains("Yubico U2F EE Serial"));
    }

    @Test
    public void specAuthenticationResponseLayoutParsesWithHandlerFraming() {
        byte[] body = concat(new byte[] {0x01}, hex("0000003B"), hex(SPEC_AUTH_SIG));

        AuthenticationBody a = AuthenticationBody.parse(body);

        assertEquals(1, a.userPresence);
        assertEquals(0x3BL, a.counter);
        assertArrayEquals(hex(SPEC_AUTH_SIG), a.sig);
        assertTrue(a.sig.length >= 8 && a.sig.length <= 72);
    }

